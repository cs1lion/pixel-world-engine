/**
 * 「一天有多长」这句**散文**，必须与代码里的 `DAY_MS` 一致。
 *
 * ## 为什么要有这个文件
 *
 * `test/memory-day.test.ts` 已经钉住了三处**代码常量**：客户端两份、服务端一份，
 * 全都得等于 24 小时。改 `DAY_MS` 会响——那条测试里 `ONE_DAY` 是个写死的字面量。
 *
 * 可同一个长度还在**十几处散文**里又写了一遍。第一版这儿写「两处散文」——
 * **那句话是假的**：2026-10-28 复审挑出来，同一种句式在全仓有 8 处，当时只守着 2 处。
 * （「8 处」是挑出来那天量的。同日全仓复量：同句式命中 **11 处**，比 8 多 3——
 * **但不写这 3 处是谁**：两次口径是否一致（当时 `docs/iterations/1027-task-1/`
 * 这类未跟踪文件算不算）没人能替那天的测量回答。复量能说的只有「现在 11 处」，
 * 差值的分解是猜。）
 *
 * 今天**不收进 PROSE 表**的一份：1027 迭代任务 1 的 README
 * （docs/iterations/1027-task-1/ 目录下，1 处命中）未跟踪、还没提交。
 * 登记一个干净检出里不存在的文件，readFileSync 会在别人机器上直接
 * ENOENT 崩掉整个测试文件——比漏守一份文档糟得多。
 * （这个路径**故意不写反引号**：audit-citations 按磁盘给文件建索引，
 * 本地这个文件在，它绿；CI 是干净检出，那个文件不在，它红——
 * 一个「本地绿、CI 红」的引用比没有引用糟。）
 * 它提交之后应当收进 PROSE 表，收的时候把这两段都改成历史。
 * 现在按句式收齐了（见下面 `PROSE`），而**句式之外的仍然没有守**：
 *
 * - `GLOSSARY.md`：「记忆按天归档的单位，一天是 24 个世界小时。」
 * - `docs/adr/ADR_MEMORY.md`：「一天 = 24 个世界小时」
 * - `docs/iterations/README.md`：5 处（那张表自己也写着「同一个长度在仓库里写了
 *   好多遍，本身就是把 24 小时当既定事实」——那句话与「只有两处」直接矛盾）
 * - `src/world/memory/config.ts`、`src/world/report.ts` ×2：代码注释
 *
 * **句式换了的这些，本文件抓不到，今天也没有别的东西抓**：
 * `docs/adr/ADR_WORLD_ALIVE.md`「一个世界日就是 24 小时」、
 * `server/memory/snapshot.py`「一天就是 24 个世界小时」与「一个世界日：24 个世界小时」、
 * `src/world/lampoil.ts`「24 个世界小时」、
 * `src/world/creator/config.ts`「一个世界日 = 24 世界小时」。
 * 它们今天都写着 24，与代码一致；可「一致」是**今天量出来的**，不是有人守着的。
 * 别把上面那份清单读成覆盖。
 *
 * 于是漂的方向只剩一种，而它恰好是代码那条拦不住的：
 * **代码没动，话被改错了**。谁把词典那句改成「12 个世界小时」——手滑、复制粘贴、
 * 或者从某份外部设计资料里抄了个 `day_length_seconds = 900` 进来——代码照旧绿，
 * 而「读那一份就够」的词典从此指向一个错的世界。
 *
 * `docs/iterations/README.md` 记着这个缺口**怎么来的又怎么补上**：它第 31 行写着
 * 「补之前这里写的是『散文那两处没有闸，所以这一条本身也会漂』；**那句话在新闸
 * 立起来的那一刻就成了假话，所以改对**」。
 * （第一版在这个位置引了一句「原话」——「散文那两处没有闸，所以这一条本身也会漂
 * ——要复核就重新数一遍，别信这张表」。**那个句子在 README 里不存在**：前半句在
 * 第 31 行且后面接的是「那句话……成了假话」，后半句在第 35 行且写的是「别信**这张**
 * 表」。两句拼成一句，还拼反了意思——README 今天说的是缺口**已补**，而第一版
 * 拿它当「README 已经承认这个缺口」的证据。）
 * 这个文件就是那道闸。别信那张表，也别信这个文件——两个都只是把「今天量出来
 * 是多少」钉住，好让明天改了的时候有东西会响。
 *
 * ## 今天量出来（2026-10-28）
 *
 * 三处代码常量，五份散文（2026-10-28 复量共 10 处命中）。
 * （这句原来写「五处说同一个长度，两处代码两份散文——不，三处代码两份散文」：
 * 「三处代码」对，「两份散文」在它自己那张表面前就错了——表里散文有五行。
 * 补三个文件那天没人回来更新这句话，于是「纠正过的版本」又漂了一次。）
 *
 * | 位置 | 形状 | 今天 | 谁守着 |
 * |---|---|---|---|
 * | `src/world/memory/config.ts` `DAY_MS` | 代码常量 | 24h | `memory-day.test.ts` |
 * | `src/world/lampoil.ts` `LAMP_DAY_MS` | 代码常量 | 24h | `memory-day.test.ts` |
 * | `server/memory/snapshot.py` `DAY_MS` | 代码常量 | 24h | `memory-day.test.ts` |
 * | `GLOSSARY.md` | 散文 | 24 | **本文件** |
 * | `docs/adr/ADR_MEMORY.md` | 散文 | 24 | **本文件** |
 * | `docs/iterations/README.md` ×5 | 散文 | 24 | **本文件**（2026-10-28 补） |
 * | `src/world/memory/config.ts` 注释 | 散文 | 24 | **本文件**（同日补） |
 * | `src/world/report.ts` ×2 | 散文 | 24 | **本文件**（同日补） |
 *
 * 服务端那份**代码常量**本文件不重复读——`memory-day.test.ts` 已经读了一遍，
 * 再读一遍只是把同一段解析抄两遍，而抄的那份会先烂。本文件只补它没管的那些散文。
 *
 * ## 判据：散文里那个数与 `DAY_MS` 换算出来的小时数相等
 *
 * 散文两种写法都认（`一天是 24 个世界小时` / `一天 = 24 个世界小时`），
 * 中间那个「是」或「=」可有可无，数字前后允许空格。今天六份文档都命中。
 *
 * （原来这儿写「每份含『世界小时』的行都只有 1 行（`report.ts` 是唯一两份的）」——
 * **那句话当场否掉自己**：括号承认有一份是两行，主句却说每份只有 1 行。
 * 2026-10-28 复量，含「世界小时」字样的行数：README 6、`report.ts` 2、
 * `memory/config.ts` 2、其余各 1。**命中的每一处都单独与 expected 比**，
 * 所以行数多不是洞——是这句话写错了。别把它抄回来。）
 *
 * **`_Avoid_:` 行整个跳过。** `GLOSSARY.md` 通篇使用这个约定，而词典最爱举的
 * 反例正是数字。（原来这儿写「今天十几条」——2026-10-28 复量是 **34 条**，
 * 「十几条」在任何读法下都不是 34。**数不钉在这儿**：它随词典每长一条就漂一次，
 * 而没有任何东西守着它，于是它会安静地假下去，正是这个文件自己警告的那类。
 * 要点是「通篇使用」，不是几条。实测过：34 条 `_Avoid_:` 行过滤器全都跳过，
 * 一条没漏——词典那种行全是行首顶格写，没有 `-` 也没有反引号开头。）
 * 实测（2026-10-28）：往词典加一句
 * `_Avoid_: 别说「一天是 12 个世界小时」——正确的是 24`，闸门红，报
 * 「GLOSSARY.md 写 12 个世界小时……把散文改回与代码一致」——**那句话是假的**，
 * 文档本来就没不一致，它举的是一个错值当反例。红得没有道理的红会让人不再读它。
 * 过滤之后同一个变异全绿。代价说清：整份文档都写成 `_Avoid_:` 反例时，
 * 「找不到」会红——而那正是要人回来看的意思。
 *
 * 反过来说：这条判据只认「一天 N 个世界小时」这一种句式。散文改成
 * 「一个世界日合 24 小时」它就抓不到，于是下面「找不到」会红。
 * 那正是要人回来重新指路的意思，**不是**去把新句式悄悄加进来而不看它——
 * 加一种句式就等于承认这个长度可以换一种说法，而换说法的时候最容易改错数。
 *
 * ## 这一条**不**查什么
 *
 * - **不查那句话说得对不对。** 「记忆按天归档的单位」是不是真的按天归档，
 *   这条管不着——语义只有人能核。
 * - **不查 `DAY_MS` 本身该是几小时。** 它只问散文与代码是否一致。真要改成
 *   12 小时制，代码、散文、`docs/SPEC_V2.md` 一起改，这条会一路护航。
 * - **不查别处出现的 `86400000`。** 样例载荷、测试数据里也有这个数，
 *   那些不定义一天有多长（`docs/iterations/README.md` 记了这条分界）。
 */

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { DAY_MS } from '../src/world/memory/config.ts';

/** 散文里的「一天 N 个世界小时」。`是`/`=` 可有可无，数字前后容忍空格。 */
const DAY_IN_PROSE = /一天\s*[是为=＝]?\s*(\d+)\s*个世界小时/g;

/**
 * 散文在哪儿、以及那句话负责什么——红的时候要能说出是哪一份漂了。
 *
 * 键是仓库根相对路径。**同一个长度在仓库里写了十几遍，这里只收同一种句式的**
 * ——见文件头「今天量出来」那一节：句式中包括了「一天 N 个世界小时」的全部
 * 变体（`是` / `=` / 什么都没有），而「一个世界日就是 24 小时」「24 个世界小时」
 * 这类**换个说法的**不在这儿，这个判据也抓不到它们。那是已知的缺口，不是漏收。
 *
 * `docs/iterations/README.md` 那张表点名了前两处，所以它们不是「顺带找到的」。
 * 剩下三处是 2026-10-28 复审挑出来的：README 自己也写着「同一个长度在仓库里写了
 * 好多遍」，而当时这个文件只守着两处——那句话是假的，现在按句式收齐了。
 */
const PROSE: Readonly<Record<string, string>> = {
  'GLOSSARY.md': '词典那条——「读那一份就够」的那一份',
  'docs/adr/ADR_MEMORY.md': '定了「一天 = 24 个世界小时」的那份 ADR',
  // 下面三处 2026-10-28 补。补之前文件头写着「同一个长度还在两处散文里又写了
  // 一遍」——那句话是假的：同句式在全仓有 8 处，当时只守着 2 处。
  'docs/iterations/README.md': '迭代日志那张表——它自己写着「同一个长度在仓库里写了好多遍」',
  'world-client/src/world/memory/config.ts': '`DAY_MS` 自己那个文件的注释——常量与它上面那句散文在同一份里',
  'world-client/src/world/report.ts': '日报那两处引用（`lampoil.ts:59` 与 `lampDayOf`）',
};

test('散文里那个小时数与代码里的 DAY_MS 对得上', () => {
  const expected = DAY_MS / (60 * 60 * 1000);
  assert.ok(
    Number.isInteger(expected),
    `DAY_MS 换算不出整数小时（${DAY_MS}ms）——这条判据只按「小时」比，`
      + '非整数说明一天的长度换了单位，回来把判据一起改对，别把这条删掉。',
  );

  const drift: string[] = [];
  for (const [rel, what] of Object.entries(PROSE)) {
    const text = readFileSync(new URL(`../../${rel}`, import.meta.url), 'utf8');
    // `_Avoid_:` 行是「别这么说」，不是在说一天有多长。`GLOSSARY.md` 通篇使用这个
    // 约定（条数不钉在这儿——理由见文件头，2026-10-28 这儿原来写「今天十几条」，
    // 复量 34 条，而这句话与文件头那条修正是同一个数的两份副本：改一份漏一份），
    // 而词典最爱举的反例正是数字——「别说一天是 12 个世界小时，
    // 正确的是 24」这句话是对的，可正则照样抓出那个 12。实测过：加上这一行，
    // 闸门红，报「把散文改回与代码一致」——而散文本来就没不一致。
    // 红得没有道理的红会让人不再读它，所以这种行整个跳过。
    const claims = text
      .split('\n')
      .filter((line) => !/^\s*(?:[-*+]\s*|>\s*)?_Avoid_:/.test(line))
      .join('\n');
    const found = [...claims.matchAll(DAY_IN_PROSE)].map((hit) => Number(hit[1]));

    assert.ok(
      found.length > 0,
      `${rel} 里找不到「一天 N 个世界小时」这句话了（${what}）。`
        + '这句话没了，这条判据就失去对象。两种可能：句子被改写了，或者这个长度'
        + '换了说法。两种都该回来看——回来把 DAY_IN_PROSE 改对，别把这条删掉。'
        + '（注意：整份文档都写成 `_Avoid_:` 反例也会走到这儿——那说明这个长度'
        + '在它那儿只以「别这么说」的形式存在，这种文档不该由本文件守。）',
    );

    for (const hours of found) {
      if (hours !== expected) {
        drift.push(`${rel} 写 ${hours} 个世界小时，而 DAY_MS 是 ${expected} 小时`);
      }
    }
  }

  assert.deepEqual(
    drift,
    [],
    `散文与代码对「一天有多长」说法不一致：${drift.join('；')}。`
      + '代码那三处由 memory-day.test.ts 守着，改 DAY_MS 它会先红；这一条红说明'
      + '**代码没动而话被改错了**。两种处置：把散文改回与代码一致，或者（如果新的'
      + '长度是刻意定的）连 DAY_MS 一起改——那 memory-day.test.ts 会拦，'
      + 'docs/SPEC_V2.md 与 docs/iterations/README.md 也得跟着改。',
  );
});
